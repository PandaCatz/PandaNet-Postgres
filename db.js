'use strict';
// PostgreSQL storage layer for PandaNet.
//
// Everything the rest of the server needs from the database lives here, exposed
// as one async method per query so callers never build SQL. Two Postgres
// gotchas are handled centrally rather than at each call site:
//
//   1. int8 (BIGINT) arrives from pg as a STRING by default, because a 64-bit
//      integer does not always fit a JS number. Every BIGINT here is a
//      millisecond timestamp or a score, all far below Number.MAX_SAFE_INTEGER,
//      so they are parsed back to numbers. Without this, `now() - run.startedAt`
//      would silently become string arithmetic.
//   2. Timestamps MUST be BIGINT, not INTEGER. Date.now() is ~1.7e12 and
//      overflows Postgres's 32-bit INTEGER, which SQLite's flexible INTEGER
//      hid completely.

const { Pool, types } = require('pg');

// OID 20 = int8. See note (1) above.
types.setTypeParser(20, v => (v === null ? null : Number(v)));

const SCHEMA = `
CREATE TABLE IF NOT EXISTS players (
  id       TEXT PRIMARY KEY,
  secret   TEXT   NOT NULL,
  name     TEXT   NOT NULL,
  created  BIGINT NOT NULL,
  "lastSeen" BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS games (
  id  TEXT PRIMARY KEY,
  cfg JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS runs (
  id          TEXT PRIMARY KEY,
  game        TEXT   NOT NULL,
  player      TEXT   NOT NULL,
  day         TEXT   NOT NULL,
  "startedAt"  BIGINT NOT NULL,
  "finishedAt" BIGINT,
  score       BIGINT,
  rooms       INTEGER,
  flagged     BOOLEAN NOT NULL DEFAULT FALSE,
  status      TEXT   NOT NULL DEFAULT 'open'
);
CREATE INDEX IF NOT EXISTS runs_player ON runs(player, day);
CREATE INDEX IF NOT EXISTS runs_open   ON runs(status, "startedAt");
CREATE TABLE IF NOT EXISTS scores (
  game    TEXT   NOT NULL,
  day     TEXT   NOT NULL,
  player  TEXT   NOT NULL,
  score   BIGINT NOT NULL,
  rooms   INTEGER NOT NULL,
  "runId"   TEXT   NOT NULL,
  updated BIGINT NOT NULL,
  PRIMARY KEY (game, day, player)
);
CREATE INDEX IF NOT EXISTS scores_board ON scores(game, day, score DESC);
-- Serves the all-time board's DISTINCT ON (player) ... ORDER BY player, score
-- DESC, updated. Without it that query is a full scan of every score row for
-- the game plus a disk-spilling sort — several seconds once a game has a few
-- hundred thousand rows — and it is reachable unauthenticated, so a single
-- client can hold the whole connection pool and stall every other endpoint.
CREATE INDEX IF NOT EXISTS scores_alltime ON scores(game, player, score DESC, updated ASC);
CREATE TABLE IF NOT EXISTS ghosts (
  game    TEXT   NOT NULL,
  day     TEXT   NOT NULL,
  player  TEXT   NOT NULL,
  score   BIGINT NOT NULL,
  log     BYTEA  NOT NULL,
  updated BIGINT NOT NULL,
  PRIMARY KEY (game, day)
);
CREATE TABLE IF NOT EXISTS events (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  game       TEXT NOT NULL,
  "startDay" TEXT NOT NULL,
  "endDay"   TEXT NOT NULL,
  data       JSONB NOT NULL
);
CREATE INDEX IF NOT EXISTS events_window ON events(game, "startDay", "endDay");
`;

// Shared by the standalone helpers and by the transactional finishRun below,
// so the two can never drift apart.
const SCORE_PUT_SQL = `INSERT INTO scores (game, day, player, score, rooms, "runId", updated)
  VALUES ($1,$2,$3,$4,$5,$6,$7)
  ON CONFLICT (game, day, player) DO UPDATE
    SET score = excluded.score, rooms = excluded.rooms,
        "runId" = excluded."runId", updated = excluded.updated
  WHERE excluded.score > scores.score`;
const GHOST_PUT_SQL = `INSERT INTO ghosts (game, day, player, score, log, updated)
  VALUES ($1,$2,$3,$4,$5,$6)
  ON CONFLICT (game, day) DO UPDATE
    SET player = excluded.player, score = excluded.score,
        log = excluded.log, updated = excluded.updated
  WHERE excluded.score > ghosts.score`;

function makeDb(connectionString, opts = {}) {
  const pool = new Pool({
    connectionString,
    max: +(process.env.PG_POOL_MAX || opts.max || 10),
    idleTimeoutMillis: 30_000,
    connectionTimeoutMillis: 10_000,
    // A client-side deadline. Without it, a connection stalled on a
    // dead-but-open socket (managed failover, silent network drop) is never
    // reclaimed: the pool leaks that slot permanently and, once all of them
    // are stranded, the process serves 500s forever without ever exiting or
    // self-healing. On timeout pg errors the query and the pool destroys and
    // replaces the client.
    query_timeout: +(process.env.PG_QUERY_TIMEOUT_MS || 15_000),
    keepAlive: true,
    // NOTE: an sslmode in the connection string is parsed AFTER this object is
    // merged and always wins, so anything set here is ignored whenever
    // DATABASE_URL carries sslmode. In pg 8.x `sslmode=require` means FULL
    // verification; `sslmode=no-verify` is the mode that skips chain
    // verification. This option therefore applies only when the URL sets no
    // sslmode at all. See the TLS section of the README.
    ssl: opts.ssl,
  });

  // A pool error (server restart, network blip) is emitted on the pool, and an
  // unhandled 'error' event would take the process down.
  pool.on('error', e => console.error(new Date().toISOString(), 'pg pool error', e.message));

  const one = async (sql, params) => (await pool.query(sql, params)).rows[0] ?? null;
  const all = async (sql, params) => (await pool.query(sql, params)).rows;
  const run = async (sql, params) => { await pool.query(sql, params); };

  return {
    pool,
    async migrate() { await pool.query(SCHEMA); },
    async close() { await pool.end(); },

    // --- players
    playerGet: id => one('SELECT * FROM players WHERE id = $1', [id]),
    playerNew: (id, secret, name, created, lastSeen) =>
      run(`INSERT INTO players (id, secret, name, created, "lastSeen") VALUES ($1,$2,$3,$4,$5)
           ON CONFLICT (id) DO NOTHING`, [id, secret, name, created, lastSeen]),
    playerTouch: (t, id) => run('UPDATE players SET "lastSeen" = $1 WHERE id = $2', [t, id]),
    playerName: (name, id) => run('UPDATE players SET name = $1 WHERE id = $2', [name, id]),

    // --- per-game config
    gameGet: id => one('SELECT cfg FROM games WHERE id = $1', [id]),
    gameAll: () => all('SELECT id, cfg FROM games'),
    gamePut: (id, cfg) =>
      run(`INSERT INTO games (id, cfg) VALUES ($1, $2)
           ON CONFLICT (id) DO UPDATE SET cfg = excluded.cfg`, [id, JSON.stringify(cfg)]),

    // --- runs
    runNew: (id, game, player, day, startedAt) =>
      run(`INSERT INTO runs (id, game, player, day, "startedAt") VALUES ($1,$2,$3,$4,$5)`,
        [id, game, player, day, startedAt]),
    runGet: id => one('SELECT * FROM runs WHERE id = $1', [id]),
    // Returns the row only if it was still open, so a concurrent double-finish
    // loses the race instead of both submissions being accepted. In SQLite this
    // was safe by virtue of a single writer; Postgres needs it stated.
    runFinish: (finishedAt, score, rooms, flagged, id) =>
      one(`UPDATE runs SET "finishedAt"=$1, score=$2, rooms=$3, flagged=$4, status='done'
           WHERE id=$5 AND status='open' RETURNING id`,
        [finishedAt, score, rooms, flagged, id]),
    runSweep: before => run(`DELETE FROM runs WHERE status='open' AND "startedAt" < $1`, [before]),

    // Close the run AND record its score as ONE transaction on ONE connection.
    // Done as separate round trips these can half-succeed: the run flips to
    // 'done' and the score write then fails (failover, pool timeout), which
    // burns the run permanently — the client's retry gets 409, which the SDK
    // correctly reads as "already recorded", so the score is lost silently.
    // Inside a transaction a failure rolls the run back to 'open' and the
    // retry re-runs the whole submission.
    //
    // 409-on-retry still exists and should: if COMMIT succeeded but its ack was
    // lost, the run really is closed and scored. What this removes is 409's
    // second, dishonest meaning of "closed and NOT recorded".
    async finishRunTx({ t, score, rooms, flagged, id, game, day, player, log }) {
      const c = await pool.connect();
      try {
        await c.query('BEGIN');
        const r = await c.query(
          `UPDATE runs SET "finishedAt"=$1, score=$2, rooms=$3, flagged=$4, status='done'
             WHERE id=$5 AND status='open' RETURNING id`,
          [t, score, rooms, flagged, id]);
        if (!r.rows[0]) { await c.query('ROLLBACK'); return { closed: false, cur: null }; }
        let cur = null;
        if (!flagged) {
          await c.query(SCORE_PUT_SQL, [game, day, player, score, rooms, id, t]);
          cur = (await c.query(
            'SELECT * FROM scores WHERE game=$1 AND day=$2 AND player=$3',
            [game, day, player])).rows[0] ?? null;
          if (log && cur && cur.runId === id) {
            await c.query(GHOST_PUT_SQL, [game, day, player, score, log, t]);
          }
        }
        await c.query('COMMIT');
        return { closed: true, cur };
      } catch (e) {
        await c.query('ROLLBACK').catch(() => {});
        throw e;
      } finally {
        c.release();
      }
    },

    // --- scores
    scoreGet: (game, day, player) =>
      one('SELECT * FROM scores WHERE game = $1 AND day = $2 AND player = $3', [game, day, player]),
    scorePut: (game, day, player, score, rooms, runId, updated) =>
      run(SCORE_PUT_SQL, [game, day, player, score, rooms, runId, updated]),
    boardTop: (game, day, limit) =>
      all(`SELECT s.player, p.name, s.score, s.rooms FROM scores s
           JOIN players p ON p.id = s.player
           WHERE s.game = $1 AND s.day = $2
           ORDER BY s.score DESC, s.updated ASC LIMIT $3`, [game, day, limit]),
    // DISTINCT ON picks the row that actually owns the player's max score, so
    // `rooms` belongs to that same run. A plain MAX() with a bare `rooms`
    // column is not even valid in Postgres, and in SQLite it silently returned
    // an arbitrary row's value.
    boardTopAll: (game, limit) =>
      all(`SELECT player, name, score, rooms FROM (
             SELECT DISTINCT ON (s.player) s.player, p.name, s.score, s.rooms
             FROM scores s JOIN players p ON p.id = s.player
             WHERE s.game = $1
             ORDER BY s.player, s.score DESC, s.updated ASC
           ) best ORDER BY score DESC LIMIT $2`, [game, limit]),
    rankDaily: (game, day, score) =>
      one('SELECT COUNT(*)::bigint AS n FROM scores WHERE game=$1 AND day=$2 AND score > $3',
        [game, day, score]),
    countDaily: (game, day) =>
      one('SELECT COUNT(*)::bigint AS n FROM scores WHERE game=$1 AND day=$2', [game, day]),

    // --- ghosts
    ghostGet: (game, day) =>
      one(`SELECT g.*, p.name FROM ghosts g JOIN players p ON p.id = g.player
           WHERE g.game = $1 AND g.day = $2`, [game, day]),
    ghostPut: (game, day, player, score, log, updated) =>
      run(GHOST_PUT_SQL, [game, day, player, score, log, updated]),

    // --- events
    eventFor: (game, day) =>
      one(`SELECT data FROM events WHERE game=$1 AND "startDay" <= $2 AND "endDay" >= $2
           ORDER BY id DESC LIMIT 1`, [game, day]),
    eventNew: (game, startDay, endDay, data) =>
      run(`INSERT INTO events (game, "startDay", "endDay", data) VALUES ($1,$2,$3,$4)`,
        [game, startDay, endDay, JSON.stringify(data)]),

    // --- health
    nPlayers: () => one('SELECT COUNT(*)::bigint AS n FROM players'),
    nGames: () => one('SELECT COUNT(DISTINCT game)::bigint AS n FROM scores'),
  };
}

module.exports = { makeDb, SCHEMA };
